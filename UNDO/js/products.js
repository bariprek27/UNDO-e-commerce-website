// Helper: get product by ID
function getProductById(id) {
  return UNDO_PRODUCTS.find(p => p.id === id) || null;
}

// Helper: get products by category
function getProductsByCategory(category) {
  if (!category || category === 'All') return UNDO_PRODUCTS;
  return UNDO_PRODUCTS.filter(p => p.category === category);
}

// Helper: get all unique categories
function getAllCategories() {
  return ['All', ...new Set(UNDO_PRODUCTS.map(p => p.category))];
}

// Helper: get featured/curated products (first 8)
function getFeaturedProducts() {
  return UNDO_PRODUCTS.slice(0, 8);
}

// Helper: get related products (same category, excluding current)
function getRelatedProducts(productId, limit = 4) {
  const product = getProductById(productId);
  if (!product) return [];
  return UNDO_PRODUCTS
    .filter(p => p.category === product.category && p.id !== productId)
    .slice(0, limit);
}

// Currency formatter
function formatPrice(amount) {
  return '₹' + amount.toLocaleString('en-IN');
}

// Condition badge colour mapping
function getConditionClass(condition) {
  const map = {
    'Like New': 'condition-like-new',
    'Excellent': 'condition-excellent',
    'Good': 'condition-good',
    'Gently Used': 'condition-gently-used'
  };
  return map[condition] || 'condition-good';
}
